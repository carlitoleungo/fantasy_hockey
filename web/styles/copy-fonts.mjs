// Copies the latin + latin-ext woff2 files we use into web/static/fonts and
// writes fonts.css (@font-face rules pointing at /static/fonts/...).
// Run after changing font weights: `npm run fonts && npm run build`.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";

const FAMILIES = {
  "ibm-plex-sans": [400, 500, 600, 700],
  "ibm-plex-mono": [400, 500, 600],
  "barlow-condensed": [500, 600, 700],
};
const SUBSETS = ["latin-ext", "latin"];
const OUT = "../static/fonts";
mkdirSync(OUT, { recursive: true });

let css = "/* Generated by copy-fonts.mjs. Fonts are SIL OFL 1.1, see /static/fonts/OFL-*.txt */\n";
for (const [fam, weights] of Object.entries(FAMILIES)) {
  const dir = `node_modules/@fontsource/${fam}`;
  copyFileSync(`${dir}/LICENSE`, `${OUT}/OFL-${fam}.txt`);
  for (const w of weights) {
    const src = readFileSync(`${dir}/${w}.css`, "utf8");
    for (const block of src.split("@font-face").slice(1)) {
      const sub = SUBSETS.find((s) => block.includes(`${fam}-${s}-${w}-normal.woff2`));
      if (!sub) continue;
      const file = `${fam}-${sub}-${w}-normal.woff2`;
      copyFileSync(`${dir}/files/${file}`, `${OUT}/${file}`);
      const body = block
        .replace(/src:[^;]+;/, `src: url(/static/fonts/${file}) format('woff2');`)
        .trim();
      css += `@font-face ${body}\n`;
    }
  }
}
writeFileSync("fonts.css", css);
console.log("fonts.css written");
